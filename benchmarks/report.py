"""Render docs/RESULTS_V2.md from outputs/benchmarks/*.json and outputs/results/telephony_eval*.json.

Every number in RESULTS_V2.md comes from a result file; nothing is typed by hand. Re-run after any benchmark:
    .venv/Scripts/python.exe benchmarks/report.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
B = ROOT / "outputs" / "benchmarks"


def load(p: Path):
    return json.loads(p.read_text()) if p.exists() else None


def table(rows: list[dict], cols: list[tuple[str, str]]) -> str:
    def fmt(v):
        if v is None:
            return "—"
        if isinstance(v, float):
            return f"{v:.4g}"
        return str(v)
    out = ["| " + " | ".join(h for h, _ in cols) + " |", "|" + "---|" * len(cols)]
    out += ["| " + " | ".join(fmt(f(r) if callable(f) else r.get(f)) for _, f in cols) + " |" for r in rows]
    return "\n".join(out)


def pct(x):
    return None if x is None else f"{100 * x:.1f}%"


RES = ROOT / "outputs" / "results"
ROB = ("clean", "mp3_64k", "telephone_mulaw_8k", "noise_20dB")
TEL_CH = ("telephone", "opus_telephone", "replay_sim")


def model_row(name: str, model_dir: Path, rob: Path, tel: Path) -> dict | None:
    vr, rb, te = load(model_dir / "val_report.json"), load(rob), load(tel)
    if vr is None:
        return None
    tw = next(iter(te["models"].values()))["all_windows"] if te else {}
    rc = rb["conditions"] if rb else {}
    return {"run": name, "val_minDCF": round(vr["pooled"]["minDCF"], 4),
            "lj_p95": vr["bonafide_p_by_source"]["ljreal"][2],
            **{f"rob_{c}": rc.get(c, {}).get("minDCF") for c in ROB},
            **{f"tel_{c}": tw.get(c, {}).get("EER") for c in TEL_CH},
            "tel_minDCF": tw.get("telephone", {}).get("minDCF")}


def training_section() -> list[str]:
    """Workstream-A runs (ml/experiments/queue.py) vs v3 on the same protocols, plus the MODEL_STRATEGY rule-1 gate."""
    base = model_row("v3 (selected)", ROOT / "models" / "selected", RES / "robustness.json", RES / "telephony_eval.json")
    runs = sorted(p.stem.removesuffix(".done") for p in (ROOT / "outputs" / "experiments").glob("*.done"))
    rows = [r for n in runs if (r := model_row(n, ROOT / "models" / f"exp_{n}", RES / f"robustness_exp_{n}.json",
                                               RES / f"telephony_eval_exp_{n}.json"))]
    if not base or not rows:
        return []

    def verdict(r):
        note = " (one generator held out of training)" if r["run"].startswith("logo_") else ""
        worse = [c for c in ROB[1:] if (r[f"rob_{c}"] or 1) > (base[f"rob_{c}"] or 0)]
        if r["val_minDCF"] >= base["val_minDCF"]:
            return f"fails: val minDCF {r['val_minDCF']} ≥ {base['val_minDCF']}{note}"
        if worse:
            return f"fails: beats v3 on val minDCF but worse on {', '.join(worse)}{note}"
        return f"passes gate 1 — still needs the ElevenLabs/2061 audit{note}"

    md = ["## Training experiments (Workstream A)", "",
          "Each run is the v3 recipe plus one controlled change (`ml/experiments/queue.py`). *val minDCF* is the "
          "pooled HEARSAY validation split; *channel suite* is the fixed 1,400-clip robustness subset "
          "(`ml/robustness.py`); *phone EER* is window-level on the simulated eval calls. EER and minDCF are "
          "threshold-free, so runs are compared without re-fitting each one's phone calibration. Gate = "
          "MODEL_STRATEGY rule 1: beat v3 on val minDCF and do not regress on MP3, µ-law or noise.", "",
          table([base, *rows], [
              ("run", "run"), ("val minDCF", "val_minDCF"), ("LJ genuine p95 p(synth)", "lj_p95"),
              *[(f"suite {c}", f"rob_{c}") for c in ROB],
              *[(f"phone EER {c}", lambda r, c=c: pct(r[f"tel_{c}"])) for c in TEL_CH],
              ("phone minDCF", "tel_minDCF"),
              ("gate", lambda r: "reference" if r is base else verdict(r))]), ""]

    uns = [u for n in runs if (u := load(RES / f"unseen_exp_{n}.json"))]
    if uns:
        md += ["Leave-one-generator-out (minDCF on the held-out generator's validation clips):", "",
               table([{**row, "exp": u["experiment"]} for u in uns for row in u["rows"]], [
                   ("run", "exp"), ("held-out generator", "generator"),
                   ("trained without it", "minDCF_model_without_it"),
                   ("v3, trained with it", "minDCF_model_trained_on_all")]), ""]
    return md


def main():
    md = ["# ProofVoice 2.0 — measured results", "",
          "_Generated by `benchmarks/report.py` from the JSON files in `outputs/benchmarks/` and `outputs/results/`. "
          "Do not edit by hand._", "",
          "All call-level detection numbers come from **simulated** calls and channels built from the HEARSAY "
          "validation set (`ml/telephony_eval`). They are not real telephone data and not production accuracy. "
          "Latency and throughput numbers come from one RTX 4060 Laptop GPU.", ""]

    bl = load(B / "backend_latency.json")
    if bl:
        md += ["## Inference backends (one 3 s window = 48,000 samples)", "",
               f"Measured {bl['created'][:16]}Z · GPU contention: {bl.get('contention')}", "",
               table([r for r in bl["results"] if r["batch"] in (1, 4, 8, 16)],
                     [("backend", "backend"), ("batch", "batch"), ("p50 ms", "p50_ms"), ("p99 ms", "p99_ms"),
                      ("ms / window", "ms_per_window"), ("windows / s", "windows_per_s"), ("peak VRAM MiB", "peak_vram_mib")]),
               "", "Prediction parity on 256 real validation windows:", "",
               table(bl["parity"]["rows"], [("candidate", "candidate"), ("reference", "reference"),
                                            ("max |Δlogit|", "max_abs_diff"), ("mean |Δlogit|", "mean_abs_diff"),
                                            ("decision agreement", lambda r: pct(r["decision_agreement"])),
                                            ("flips", "decision_flips")]), ""]

    for be in ("pytorch", "tensorrt"):
        lt = load(B / f"load_test_{be}.json")
        if not lt:
            continue
        md += [f"## Concurrent calls — {lt['machine']['backend']}", "",
               f"Measured {lt['created'][:16]}Z · {lt['call_seconds']:.0f} s calls, alternating genuine/synthetic, "
               f"streamed through the production Twilio path at real-time pace · other GPU work: "
               f"{lt['gpu_baseline'] or 'none'}", "",
               table(lt["results"], [
                   ("policy", "policy"), ("calls", "calls"), ("p50 ms", "latency_p50_ms"), ("p95 ms", "latency_p95_ms"),
                   ("p99 ms", "latency_p99_ms"), ("mean batch", "batch_mean"),
                   ("windows run", lambda r: f"{r['inferred']}/{r['hops']}"), ("shed", "shed"),
                   ("GPU util %", "gpu_util_mean_pct"), ("GPU MiB", "gpu_mem_peak_mb"),
                   ("genuine flagged", lambda r: f"{r['genuine']['suspicious']}/{r['genuine']['calls']}"),
                   ("synthetic flagged", lambda r: f"{r['synthetic']['suspicious']}/{r['synthetic']['calls']}"),
                   ("first alert s (median)", lambda r: None if r["synthetic"]["first_alert_ms_median"] is None
                    else round(r["synthetic"]["first_alert_ms_median"] / 1000, 1))]), ""]

    pr = load(B / "policy_replay.json")
    if pr:
        md += ["## Call-level policy (risk engine + Aegis gate), simulated eval calls", "",
               f"Measured {pr['created'][:16]}Z. Risk policy `H={pr['risk_policy']['H']}`, "
               f"`persist={pr['risk_policy']['persist']}`, `min_snr_db={pr['risk_policy']['min_snr_db']}` — "
               f"{pr['selection']}. Fitted on the calib split; the table is the speaker-disjoint eval split.", "",
               table(pr["results"], [
                   ("channel", "channel"), ("gating", "gating"),
                   ("genuine false alerts", lambda r: pct(r["genuine_false_alert_rate"])),
                   ("95% CI", lambda r: f"{pct(r['fa_ci95'][0])}–{pct(r['fa_ci95'][1])}"),
                   ("synthetic detected", lambda r: pct(r["synthetic_detection_rate"])),
                   ("mixed detected after switch", lambda r: pct(r["mixed_detection_rate"])),
                   ("first alert s p50", "first_alert_s_p50"), ("p95", "first_alert_s_p95"),
                   ("usable speech at alert s p50", "first_alert_usable_speech_s_p50"),
                   ("synthetic abstain", lambda r: pct(r["synthetic_abstain_rate"])),
                   ("compute", lambda r: pct(r["compute_fraction"]))]), "",
               "Adaptive gating vs fixed-rate inference (same calls, same risk policy):", "",
               table(pr["adaptive_vs_fixed"], [
                   ("channel", "channel"), ("compute reduction", lambda r: pct(r["compute_reduction"])),
                   ("Δ false alerts", lambda r: pct(r["delta_false_alert"])),
                   ("Δ detection", lambda r: pct(r["delta_detection"])), ("Δ first alert s", "delta_first_alert_s_p50")]), ""]

    sr, cr = load(B / "screen_ratio.json"), load(B / "cascade_replay.json")
    if cr:
        md += ["## Two-stage screening (distilled 4-layer student → 12-layer model)", "",
               f"Measured {cr['created'][:16]}Z. Student `{cr['student']}`; cost ratio student/main = "
               f"{cr['cost_ratio']} per window" + (f" (from `screen_ratio.json`: " + ", ".join(
                   f"batch {r['batch']}: {r['ratio']}" for r in sr["results"]) + "; other GPU work: "
                   + ("yes — training job" if sr["other_gpu_processes"] != "none" else "none") + ")" if sr else "")
               + ". Cost is relative to fixed-rate inference on every hop.", "",
               table([r for r in cr["results"] if r["channel"] in ("telephone", "clean")], [
                   ("channel", "channel"), ("student clear threshold (llr)", "screen_clear_llr"),
                   ("genuine false alerts", lambda r: pct(r["genuine_false_alert_rate"])),
                   ("synthetic detected", lambda r: pct(r["synthetic_detection_rate"])),
                   ("first alert s p50", "first_alert_s_p50"), ("main-model windows", "main_windows"),
                   ("student windows", "student_windows"), ("cost", "cost_vs_fixed_rate")]), "",
               "Negative result: every cascade setting costs more than adaptive gating alone, because the student "
               "shares the full convolutional front end (it is only ~1/3 cheaper) and is rarely confident on "
               "narrowband speech. Two-stage screening stays off by default (`AEGIS_SCREEN_MODEL_DIR` unset).", ""]

    te = load(ROOT / "outputs" / "results" / "telephony_eval.json")
    if te:
        md += ["## Window-level detector on simulated channels", "",
               "See `docs/research/telephony_eval.md` for the method, per-speaker spread, calibration and quality "
               "gates; raw numbers in `outputs/results/telephony_eval.json`.", ""]

    md += training_section()

    out = ROOT / "docs" / "RESULTS_V2.md"
    out.write_text("\n".join(md) + "\n", encoding="utf-8")
    print("wrote", out)


if __name__ == "__main__":
    main()
